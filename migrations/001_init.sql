-- NeuroLens schema: users, jobs, credit ledger, workers, payments.
-- Balances live on users; every change to them is also an append-only ledger row (see 002).

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE job_status AS ENUM
  ('AWAITING_UPLOAD', 'UPLOADED', 'PROCESSING', 'SUCCEEDED', 'FAILED', 'EXPIRED', 'CANCELLED');

CREATE TYPE ledger_kind AS ENUM
  ('GRANT', 'PURCHASE', 'SUBSCRIPTION_GRANT', 'RESERVE', 'ADJUST', 'CAPTURE', 'RELEASE');

CREATE TABLE users (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  google_sub         text UNIQUE,                 -- NULL for dev / load-test users
  email              text NOT NULL UNIQUE,
  name               text,
  avatar_url         text,
  credits_available  integer NOT NULL DEFAULT 0 CHECK (credits_available >= 0),
  credits_reserved   integer NOT NULL DEFAULT 0 CHECK (credits_reserved >= 0),
  stripe_customer_id text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  last_login_at      timestamptz
);

CREATE TABLE jobs (
  id                   uuid PRIMARY KEY,           -- generated by the web tier, embedded in the S3 key
  user_id              uuid NOT NULL REFERENCES users(id),
  status               job_status NOT NULL DEFAULT 'AWAITING_UPLOAD',
  original_filename    text NOT NULL,
  content_type         text NOT NULL,
  size_bytes           bigint NOT NULL,
  s3_input_key         text NOT NULL,
  s3_result_key        text,
  est_duration_s       numeric(8,2) NOT NULL,      -- from the browser
  actual_duration_s    numeric(8,2),               -- from ffprobe on the worker
  credits_reserved     integer NOT NULL DEFAULT 0 CHECK (credits_reserved >= 0),
  credits_captured     integer,
  attempts             integer NOT NULL DEFAULT 0,
  worker_id            text,
  progress_stage       text,
  progress_pct         smallint,
  heartbeat_at         timestamptz,
  error_code           text,
  error_message        text,
  summary              jsonb,
  prewarm_action       text,
  cold_start           boolean,
  gpu_device           text,
  gpu_peak_vram_gb     numeric(6,2),
  -- Experiment 1 stage timestamps
  created_at           timestamptz NOT NULL DEFAULT now(),
  upload_confirmed_at  timestamptz,
  s3_event_at          timestamptz,
  claimed_at           timestamptz,
  downloaded_at        timestamptz,
  validated_at         timestamptz,
  pass_full_done_at    timestamptz,
  pass_silent_done_at  timestamptz,
  roi_done_at          timestamptz,
  completed_at         timestamptz,
  client_render_ms     integer
);
CREATE INDEX jobs_user_created ON jobs (user_id, created_at DESC);
CREATE INDEX jobs_active ON jobs (status, created_at)
  WHERE status IN ('AWAITING_UPLOAD', 'UPLOADED', 'PROCESSING');

CREATE TABLE credit_ledger (
  id               bigserial PRIMARY KEY,
  user_id          uuid NOT NULL REFERENCES users(id),
  job_id           uuid REFERENCES jobs(id),
  kind             ledger_kind NOT NULL,
  delta_available  integer NOT NULL,
  delta_reserved   integer NOT NULL,
  ref              text,                 -- Stripe session / invoice id, signup marker, or release reason
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ledger_user ON credit_ledger (user_id, created_at);
-- Idempotency: a job is reserved, captured and released at most once;
-- a grant / purchase reference is credited at most once.
CREATE UNIQUE INDEX ledger_job_once ON credit_ledger (job_id, kind)
  WHERE kind IN ('RESERVE', 'CAPTURE', 'RELEASE');
CREATE UNIQUE INDEX ledger_ref_once ON credit_ledger (kind, ref)
  WHERE kind IN ('GRANT', 'PURCHASE', 'SUBSCRIPTION_GRANT');

CREATE TABLE workers (
  instance_id          text PRIMARY KEY,
  instance_type        text,
  lifecycle            text,             -- spot | on-demand | local
  launched_at          timestamptz,
  container_started_at timestamptz,
  model_loaded_at      timestamptz,
  warm_ready_at        timestamptz,
  last_job_at          timestamptz,
  jobs_completed       integer NOT NULL DEFAULT 0,
  terminated_at        timestamptz,
  termination_reason   text              -- idle | spot | error
);

CREATE TABLE payments (
  stripe_session_id text PRIMARY KEY,
  user_id           uuid NOT NULL REFERENCES users(id),
  pack_id           text NOT NULL,
  credits           integer NOT NULL,
  amount_cents      integer NOT NULL,
  currency          text NOT NULL,
  status            text NOT NULL,       -- created | paid
  created_at        timestamptz NOT NULL DEFAULT now(),
  paid_at           timestamptz
);
